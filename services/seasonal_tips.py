# services/seasonal_tips.py

from datetime import datetime


def get_seasonal_tips() -> str:
    """Отримання сезонних порад"""
    month = datetime.now().month

    if month in [12, 1, 2]:  # Зима
        return (
            "❄️ <b>Зимові поради:</b>\n\n"
            "• Перевірте акумулятор (в холодну погоду ємність падає на 30-40%)\n"
            "• Замініть рідину омивача на зимову\n"
            "• Перевірте тиск у шинах\n"
            "• Встановіть зимові шини\n"
            "• Перевірте підігрів сидінь та керма\n\n"
            "<i>Потрібна допомога? Звертайтесь!</i>"
        )
    elif month in [3, 4, 5]:  # Весна
        return (
            "🌱 <b>Весняні поради:</b>\n\n"
            "• Перевірте кондиціонер перед літом\n"
            "• Замініть щітки склоочисника\n"
            "• Перевірте підвіску після зимових ям\n"
            "• Зробіть діагностику після зими\n\n"
            "<i>Запишіться на весняний огляд!</i>"
        )
    elif month in [6, 7, 8]:  # Літо
        return (
            "☀️ <b>Літні поради:</b>\n\n"
            "• Перевірте систему охолодження\n"
            "• Заправте кондиціонер\n"
            "• Перевірте тиск у шинах (в спеку зростає)\n"
            "• Слідкуйте за температурою двигуна\n\n"
            "<i>Кондиціонер не холодить? Ми допоможемо!</i>"
        )
    else:  # Осінь
        return (
            "🍂 <b>Осінні поради:</b>\n\n"
            "• Підготуйте авто до холодів\n"
            "• Перевірте опалення\n"
            "• Замініть гумові ущільнювачі\n"
            "• Перевірте світло (дні стають коротшими)\n\n"
            "<i>Зробіть осінню діагностику!</i>"
        )